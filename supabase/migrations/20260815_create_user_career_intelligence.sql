grant select on table public.user_entitlements to authenticated;
grant usage, select on sequence public.saved_career_markets_id_seq, public.saved_career_comparisons_id_seq, public.career_alert_subscriptions_id_seq, public.career_opportunity_reports_id_seq to authenticated;

create index saved_career_markets_user_idx on public.saved_career_markets (user_id, updated_at desc);
