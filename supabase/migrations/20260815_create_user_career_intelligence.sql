create policy "Users manage their saved career markets" on public.saved_career_markets for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Users manage their saved comparisons" on public.saved_career_comparisons for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Users manage their career alerts" on public.career_alert_subscriptions for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Users read and create their opportunity reports" on public.career_opportunity_reports for select to authenticated using (user_id = auth.uid());
create policy "Users create their opportunity reports" on public.career_opportunity_reports for insert to authenticated with check (user_id = auth.uid());
create policy "Users read their entitlements" on public.user_entitlements for select to authenticated using (user_id = auth.uid());

revoke all privileges on table public.user_career_profiles, public.saved_career_markets, public.saved_career_comparisons, public.career_alert_subscriptions, public.career_opportunity_reports, public.user_entitlements from public, anon;
grant select, insert, update, delete on table public.user_career_profiles, public.saved_career_markets, public.saved_career_comparisons, public.career_alert_subscriptions to authenticated;
